import assert from 'node:assert/strict';
import { normal, toxic } from './public/js/digestive-data.js';
import { createAnatomy } from './public/js/anatomy.js';
import { createFoodParticle } from './public/js/food-particle.js';

assert.equal(normal.length, 7);
assert.equal(toxic.length, 4);
const model = createAnatomy();
assert.equal(model.organs.length, 7);
for (let i = 0; i < 6; i++) assert.ok(model.organs[i].curve.getPoint(1).distanceTo(model.organs[i + 1].curve.getPoint(0)) < 1e-6);
for (const organ of model.organs) {
  assert.ok([...organ.mesh.geometry.attributes.position.array].every(Number.isFinite));
  assert.equal(organ.mesh.material.roughness, 0.25);
  assert.equal(organ.mesh.material.clearcoat, 1);
}
assert.equal(Object.keys(model.accessories).length, 3);
const stomachPoints = model.organs[2].curve.points;
assert.ok(Math.max(...stomachPoints.map(point => point.x)) > 1);
assert.ok(stomachPoints.at(-1).x < stomachPoints[0].x);
assert.ok(model.organs[3].curve.points.some(point => point.x < -0.9));
for (const organ of Object.values(model.accessories)) {
  organ.geometry.computeBoundingBox();
  assert.ok([...organ.geometry.attributes.position.array].every(Number.isFinite));
}
assert.ok(model.accessories.liver.position.x < 0);
assert.ok(model.accessories.gallbladder.position.y < model.accessories.liver.position.y);
const stomachBase = model.organs[2].mesh.geometry.attributes.position.array.slice();
model.react(2, 'toxic', 'vomit', 0.2, 1);
assert.notDeepEqual(model.organs[2].mesh.geometry.attributes.position.array, stomachBase);
model.react(2, 'normal', 'vomit', 0.2, 1);
assert.deepEqual(model.organs[2].mesh.geometry.attributes.position.array, stomachBase);
const intestineColor = model.organs[4].mesh.material.color.clone();
model.react(4, 'toxic', 'diarrhea', 1, 1);
assert.ok(!model.organs[4].mesh.material.color.equals(intestineColor));
model.react(4, 'normal', 'diarrhea', 1, 1);
assert.ok(model.organs[4].mesh.material.color.equals(intestineColor));
const journey = createFoodParticle(model.organs);
journey.seek(0.45);
assert.equal(journey.stageIndex, 4);
const size = journey.mesh.scale.x;
journey.seek(0.66);
assert.ok(journey.mesh.scale.x < size);
journey.setMode('toxic', 'vomit');
journey.seek(0.23);
journey.playing = true;
journey.update(1);
assert.equal(journey.direction, -1);
const turning = journey.progress;
journey.update(1);
assert.ok(Math.abs(journey.progress - (turning - 2 / 9)) < 1e-8);
assert.equal(journey.mesh.material.color.getHexString(), '22c55e');
journey.update(100);
assert.equal(journey.progress, 0);
assert.equal(journey.playing, false);
journey.setMode('toxic', 'diarrhea');
journey.seek(0.4);
journey.playing = true;
journey.update(1);
assert.ok(Math.abs(journey.progress - (0.4 + 6 / 90)) < 1e-8);
journey.playing = false;
const paused = journey.progress;
journey.update(3);
assert.equal(journey.progress, paused);
journey.setMode('normal');
assert.equal(journey.direction, 1);
assert.equal(journey.progress, 0);
assert.notEqual(journey.mesh.material.color.getHexString(), '22c55e');
journey.seek(-1);
assert.equal(journey.progress, 0);
journey.seek(2);
assert.equal(journey.progress, 1);
console.log('PASS: 7 organs, 2 scenarios, continuity, absorption, vomiting, diarrhea, pause and reset');
